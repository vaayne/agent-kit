export type Strings = typeof zh;
export const STRINGS: Record<Language, Strings> = { zh, en };

export function reasonText(t: Strings, reason: ReasonCode, pr: number | null): string {
  const base = t.reason[reason];
  return pr === null ? base : `PR #${pr} · ${base}`;
}
