export type Language = "zh" | "en";

/**
 * The plugin SDK has no locale API, so the browser's language decides unless
 * the plugin setting pins one. Every user-facing string lives here.
 */
export function resolveLanguage(setting: "auto" | Language | undefined): Language {
  if (setting === "zh" || setting === "en") return setting;
  const tag = typeof navigator === "undefined" ? "" : navigator.language;
  return tag.toLowerCase().startsWith("zh") ? "zh" : "en";
}

