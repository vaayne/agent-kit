import { type BbPluginApi, cliCommand, defineCli, type PluginCliResult } from "@get-bb/plugin-sdk";
import { createHash, randomBytes } from "node:crypto";
import { readFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import { type Catalog, parseMagpieConfig } from "./config.ts";
import { hostContract } from "./contract.ts";
import { renderExtension } from "./pi-extension.ts";
import { createProxy, gatewayURL, machineToken, routes } from "./proxy.ts";

const jsonOption = { type: "boolean", description: "Print JSON." } as const;
const machineOption = {
  type: "string",
  description: "Select one enrolled machine by name or ID. The default is all persistent machines.",
} as const;

export default async function plugin(bb: BbPluginApi) {
  const settings = bb.settings.define({
    gatewayUrl: { type: "string", label: "Magpie gateway", default: "http://127.0.0.1:3425" },
    gatewayKey: {
      type: "string",
      label: "Magpie gateway key",
      secret: true,
      default: "",
      description: "Only needed when the gateway requires a key. Kept on the BB server.",
    },
    piAgentDir: {
      type: "string",
      label: "Magpie Pi config directory",
      default: process.env.PI_CODING_AGENT_DIR || join(homedir(), ".pi", "agent"),
      description: "Directory on the BB server where Magpie writes Pi models.json and settings.json.",
    },
    codexRouting: { type: "boolean", label: "Route native Codex through Magpie", default: false },
    claudeRouting: { type: "boolean", label: "Route native Claude Code through Magpie", default: false },
    autoSync: {
      type: "boolean",
      label: "Automatically sync Pi models",
      default: false,
      description: "When enabled, sync all persistent machines every 30 seconds. Refresh Pi when its threads are idle.",
    },
    proxySecret: {
      type: "string",
      label: "Connector signing key",
      secret: true,
      default: "",
      description: "Generated by the plugin. Changing it revokes all current machine tokens.",
    },
  });
  if (!(await settings.get()).proxySecret) {
    await settings.experimental_set({ proxySecret: randomBytes(32).toString("hex") });
  }
  const host = bb.hosts.experimental_client({ contract: hostContract });
  const proxy = createProxy({
    settings: () => settings.get(),
    enrolled: async (id) => (await bb.sdk.hosts.list()).some((entry) => entry.id === id),
    onError: (error) => {
      const cause = error instanceof Error ? error.cause : undefined;
      const code = cause && typeof cause === "object" && "code" in cause ? String(cause.code) : "unknown";
      bb.log.warn(
        `Magpie gateway request failed: ${error instanceof Error ? error.message : String(error)} (${code}; ${
          cause instanceof Error ? cause.message : "no cause"
        })`,
      );
    },
  });
  bb.onDispose(() => proxy.dispose());
  for (const path of routes) {
    bb.http.route("POST", path, (context) => proxy.handle(context.req.raw, path), { auth: "none" });
  }
  for (const agent of ["codex", "claude"] as const) {
    const paths = agent === "codex"
      ? ["/v1/responses"] as const
      : ["/v1/messages", "/v1/messages/count_tokens"] as const;
    for (const path of paths) {
      bb.http.route("POST", `/${agent}${path}`, async (context) => {
        const response = await proxy.handle(context.req.raw, path, agent);
        bb.log.info(`Magpie ${agent} ${path}: HTTP ${response.status}`);
        return response;
      }, { auth: "none" });
    }
  }

  bb.providers.experimental_contributeEnv("pi", async ({ hostId }) => {
    const config = await settings.get();
    if (!config.proxySecret) throw new Error("Reload the Magpie connector to create its signing key.");
    return [
      {
        name: "BB_MAGPIE_BASE_URL",
        value: { serverPath: "/api/v1/plugins/magpie/http" },
        reason: "Route Pi through the central Magpie connector.",
      },
      {
        name: "BB_MAGPIE_TOKEN",
        value: machineToken(config.proxySecret, hostId),
        reason: "Magpie connector token for this machine.",
      },
    ];
  });
  for (const provider of ["codex", "claude-code"] as const) {
    bb.providers.experimental_contributeEnv(provider, async ({ hostId, threadId }) => {
      const config = await settings.get();
      const threadRoute = await bb.storage.kv.get<boolean>(`route:${threadId}`);
      if (!(threadRoute ?? (provider === "codex" ? config.codexRouting : config.claudeRouting))) return [];
      if (!config.proxySecret) throw new Error("Reload the Magpie connector to create its signing key.");
      const token = machineToken(config.proxySecret, hostId);
      const reason = "This thread is routed through Magpie.";
      if (provider === "codex") {
        return [
          { name: "CODEX_OPENAI_BASE_URL", value: { serverPath: "/api/v1/plugins/magpie/http/codex/v1" }, reason },
          { name: "CODEX_POOL_AUTH_TOKEN", value: token, reason },
        ];
      }
      return [
        { name: "ANTHROPIC_BASE_URL", value: { serverPath: "/api/v1/plugins/magpie/http/claude" }, reason },
        { name: "ANTHROPIC_AUTH_TOKEN", value: token, reason },
      ];
    });
  }

  async function readCatalog(): Promise<Catalog> {
    const { piAgentDir } = await settings.get();
    const [models, selection] = await Promise.all([
      readFile(join(piAgentDir, "models.json"), "utf8"),
      readFile(join(piAgentDir, "settings.json"), "utf8").catch((error: NodeJS.ErrnoException) => {
        if (error.code === "ENOENT") return "{}";
        throw error;
      }),
    ]);
    let parsedModels: unknown;
    let parsedSelection: unknown;
    try {
      parsedModels = JSON.parse(models);
      parsedSelection = JSON.parse(selection);
    } catch {
      throw new Error("Magpie Pi models.json or settings.json contains invalid JSON.");
    }
    return parseMagpieConfig(parsedModels, parsedSelection);
  }
  async function gatewayCheck() {
    const config = await settings.get();
    const response = await fetch(new URL("/api/hello", gatewayURL(config.gatewayUrl)), {
      headers: { authorization: `Bearer ${config.gatewayKey || "magpie-pi"}` },
      signal: AbortSignal.timeout(5_000),
      redirect: "error",
    });
    if (!response.ok) throw new Error(`Magpie health check returned HTTP ${response.status}.`);
    const value: unknown = await response.json();
    if (!value || typeof value !== "object" || !("name" in value) || value.name !== "magpie") {
      throw new Error("The gateway endpoint did not identify itself as Magpie.");
    }
    return { reachable: true, version: "version" in value ? String(value.version) : null };
  }
  async function machines(selector?: string) {
    const entries = (await bb.sdk.hosts.list()).filter((entry) => entry.type === "persistent");
    if (!selector) return entries;
    const selected = entries.filter((entry) => entry.id === selector || entry.name === selector);
    if (selected.length !== 1) throw new Error("Select a unique enrolled machine by name or ID.");
    return selected;
  }
  async function inspect(selector?: string) {
    return Promise.all((await machines(selector)).map(async (machine) => {
      if (machine.status !== "connected") return { machine: machine.name, hostId: machine.id, connected: false };
      try {
        return {
          machine: machine.name,
          hostId: machine.id,
          connected: true,
          ...await host.call("inspect", {}, { hostId: machine.id }),
        };
      } catch (error) {
        return { machine: machine.name, hostId: machine.id, error: message(error) };
      }
    }));
  }
  function message(error: unknown) {
    return error instanceof Error ? error.message : String(error);
  }
  let queue: Promise<unknown> = Promise.resolve();
  function serialize<T>(action: () => Promise<T>): Promise<T> {
    const result = queue.then(action);
    queue = result.catch(() => {});
    return result;
  }
  async function installCatalog(catalog: Catalog, selector?: string, automatic = false) {
    const digest = createHash("sha256").update(renderExtension(catalog)).digest("hex");
    const results = [];
    for (const machine of await machines(selector)) {
      if (automatic && await bb.storage.kv.get<boolean>(`sync-excluded:${machine.id}`)) continue;
      if (machine.status !== "connected") {
        if (!automatic) {
          results.push({
            machine: machine.name,
            ok: false,
            error: "Machine is offline. Automatic sync retries when it reconnects.",
          });
        }
        continue;
      }
      const current = await bb.storage.kv.get<string>(`catalog:${machine.id}`);
      if (automatic && current === digest) continue;
      try {
        const installed = await host.call("install", catalog, { hostId: machine.id });
        await bb.storage.kv.set(`catalog:${machine.id}`, digest);
        await bb.storage.kv.delete(`sync-excluded:${machine.id}`);
        if (current !== digest) await bb.storage.kv.set("pi-refresh-pending", true);
        results.push({ machine: machine.name, ok: true, ...installed });
      } catch (error) {
        results.push({ machine: machine.name, ok: false, error: message(error) });
      }
    }
    return results;
  }
  let disposed = false;
  let autoRunning = false;
  let lastCheck: string | null = null;
  let lastSync: string | null = null;
  let autoError: string | null = null;
  async function automaticSync() {
    if (disposed || autoRunning) return;
    autoRunning = true;
    try {
      await serialize(async () => {
        if (disposed || !(await settings.get()).autoSync) return;
        lastCheck = new Date().toISOString();
        const catalog = await readCatalog();
        const results = await installCatalog(catalog, undefined, true);
        if (results.some((result) => result.ok)) {
          lastSync = lastCheck;
          bb.log.info(
            `Synced ${catalog.models.length} Pi models to ${results.filter((result) => result.ok).length} machines.`,
          );
        }
        const failed = results.filter((result) => !result.ok);
        if (failed.length) throw new Error(failed.map((result) => `${result.machine}: ${result.error}`).join("; "));
        if (!disposed && await bb.storage.kv.get<boolean>("pi-refresh-pending")) {
          const counts = await Promise.all(
            (["active", "starting", "pending", "stopping"] as const).map((status) =>
              bb.sdk.threads.count({ providerId: "pi", status })
            ),
          );
          if (!disposed && counts.every((count) => count.total === 0)) {
            await bb.sdk.plugins.reload({ pluginId: "provider-pi" });
            await bb.storage.kv.delete("pi-refresh-pending");
            bb.log.info(
              "Refreshed the idle Pi provider. BB model pickers can retain their prior list for up to 10 minutes.",
            );
          }
        }
        autoError = null;
      });
    } catch (error) {
      const detail = message(error);
      if (!disposed && detail !== autoError) bb.log.warn(`Pi auto-sync: ${detail}`);
      autoError = detail;
    } finally {
      autoRunning = false;
    }
  }
  const syncTimer = setInterval(() => {
    void automaticSync();
  }, 30_000);
  syncTimer.unref();
  bb.onDispose(() => {
    disposed = true;
    clearInterval(syncTimer);
  });
  async function run(json: boolean | undefined, action: () => Promise<unknown>): Promise<PluginCliResult> {
    try {
      const result = await action();
      const failed = result !== null && typeof result === "object"
        && (("ok" in result && result.ok === false) || ("ready" in result && result.ready === false));
      return { exitCode: failed ? 1 : 0, stdout: JSON.stringify(result, null, json ? undefined : 2) + "\n" };
    } catch (error) {
      return {
        exitCode: 1,
        stderr: message(error) + "\n",
        ...(json ? { stdout: JSON.stringify({ ok: false, error: message(error) }) + "\n" } : {}),
      };
    }
  }
  const status = cliCommand({
    summary: "Show the gateway and Pi connector installation on enrolled machines.",
    options: { json: jsonOption, machine: machineOption },
    run: ({ options }) =>
      run(options.json, async () => {
        const config = await settings.get();
        return {
          gatewayUrl: config.gatewayUrl,
          piAgentDir: config.piAgentDir,
          gatewayKeyConfigured: Boolean(config.gatewayKey),
          nativeRouting: { codex: config.codexRouting, claude: config.claudeRouting },
          autoSync: {
            enabled: config.autoSync,
            intervalSeconds: 30,
            lastCheck,
            lastSync,
            error: autoError,
            piRefreshPending: await bb.storage.kv.get<boolean>("pi-refresh-pending") ?? false,
          },
          machines: await inspect(options.machine),
        };
      }),
  });
  bb.cli.register(defineCli({
    name: "magpie",
    summary: "Connect BB agents to a shared Magpie gateway.",
    root: status,
    commands: {
      status,
      routing: cliCommand({
        summary: "Set the default Magpie route for native Codex or Claude Code on all machines.",
        description:
          "Changes apply on the next turn. Disable Account Pooler routing for the same provider to avoid environment conflicts.",
        positionals: [{ name: "provider", required: true, description: "codex or claude." }],
        options: { json: jsonOption, off: { type: "boolean", description: "Turn off the default route." } },
        run: ({ options, positionals }) =>
          run(options.json, async () => {
            const provider = positionals.provider;
            if (provider !== "codex" && provider !== "claude") throw new Error("Select codex or claude. Pi uses sync.");
            if (!options.off) await gatewayCheck();
            await settings.experimental_set(
              provider === "codex" ? { codexRouting: !options.off } : { claudeRouting: !options.off },
            );
            return {
              provider,
              routed: !options.off,
              applies: "Next turn on all enrolled machines; per-thread overrides take precedence.",
              next: options.off
                ? "Per-thread routes remain active. Native login is needed for threads without a route."
                : `Run bb pool routing ${provider} --off if Account Pooler is enabled.`,
            };
          }),
      }),
      route: cliCommand({
        summary: "Route one native Codex or Claude Code thread through Magpie.",
        description:
          "If Account Pooler is enabled, first run bb pool bypass <thread-id>. Changes apply on the next turn.",
        positionals: [{ name: "thread", required: true, description: "BB thread ID." }],
        options: { json: jsonOption, off: { type: "boolean", description: "Remove this thread from Magpie routing." } },
        run: ({ options, positionals }) =>
          run(options.json, async () => {
            const thread = await bb.sdk.threads.get({ threadId: positionals.thread });
            if (!["codex", "claude-code"].includes(thread.providerId)) {
              throw new Error("Select a native Codex or Claude Code thread. Pi uses sync.");
            }
            if (options.off) await bb.storage.kv.set(`route:${thread.id}`, false);
            else {
              await gatewayCheck();
              await bb.storage.kv.set(`route:${thread.id}`, true);
            }
            return {
              threadId: thread.id,
              provider: thread.providerId,
              routed: !options.off,
              next: options.off
                ? `If this thread used Account Pooler, run bb pool bypass ${thread.id} --off.`
                : `Run bb pool bypass ${thread.id} if Account Pooler is enabled, then send the test prompt.`,
            };
          }),
      }),
      check: cliCommand({
        summary: "Check the Magpie gateway and its generated Pi catalog. No model request is sent.",
        options: {
          json: jsonOption,
          native: { type: "boolean", description: "Check native Codex/Claude routing without requiring Pi config." },
        },
        run: ({ options }) =>
          run(options.json, async () => {
            if (options.native) return { ready: true, gateway: await gatewayCheck() };
            const checks = await Promise.allSettled([gatewayCheck(), readCatalog()]);
            const gateway = checks[0];
            const catalog = checks[1];
            return {
              ready: gateway.status === "fulfilled" && catalog.status === "fulfilled",
              gateway: gateway.status === "fulfilled" ? gateway.value : { error: message(gateway.reason) },
              catalog: catalog.status === "fulfilled"
                ? { modelCount: catalog.value.models.length, defaultModel: catalog.value.defaultModel }
                : { error: message(catalog.reason) },
            };
          }),
      }),
      sync: cliCommand({
        summary: "Read Magpie Pi config on the server and set Pi to Magpie on connected machines.",
        options: { json: jsonOption, machine: machineOption },
        run: ({ options }) =>
          run(options.json, () =>
            serialize(async () => {
              await gatewayCheck();
              const catalog = await readCatalog();
              const results = await installCatalog(catalog, options.machine);
              return {
                ok: results.every((entry) => entry.ok),
                defaultModel: catalog.defaultModel,
                machines: results,
                next:
                  "When Pi threads are idle, run bb plugin reload provider-pi, or enable autoSync for automatic refresh.",
              };
            })),
      }),
      remove: cliCommand({
        summary: "Remove the Pi extension and restore the prior Pi selection on connected machines.",
        options: { json: jsonOption, machine: machineOption },
        run: ({ options }) =>
          run(options.json, () =>
            serialize(async () => {
              if (!options.machine) await settings.experimental_set({ autoSync: false });
              const results = [];
              for (const machine of await machines(options.machine)) {
                await bb.storage.kv.set(`sync-excluded:${machine.id}`, true);
                await bb.storage.kv.delete(`catalog:${machine.id}`);
                try {
                  results.push({
                    machine: machine.name,
                    ok: true,
                    ...await host.call("remove", {}, { hostId: machine.id }),
                  });
                } catch (error) {
                  results.push({ machine: machine.name, ok: false, error: message(error) });
                }
              }
              return {
                ok: results.every((entry) => entry.ok),
                machines: results,
                next: "When Pi threads are idle, run bb plugin reload provider-pi to refresh the model catalog.",
              };
            })),
      }),
    },
  }));
}
